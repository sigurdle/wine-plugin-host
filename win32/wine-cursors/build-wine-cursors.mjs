// Regenerates wineCursors.js from the .cur files beside it: node build-wine-cursors.mjs
// The .cur files are Wine's (dlls/user32/resources), LGPL 2.1 or later -- see NOTICE.txt.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
// The IDC_ / OCR_ id each Wine file answers (Wine dlls/user32/user32.rc, "Cursors").
const FILES = [
	[32512, "normal"], [32513, "ibeam"], [32514, "wait"], [32515, "cross"], [32516, "up"],
	[32640, "size"], [32642, "sizenwse"], [32643, "sizenesw"], [32644, "sizewe"], [32645, "sizens"],
	[32646, "sizeall"], [32648, "no"], [32649, "hand"], [32650, "appstarting"], [32651, "help"],
];
let out = "/*\n * GENERATED by build-wine-cursors.mjs from the ocr_*.cur files beside it -- do not edit.\n" +
	" * Wine's system cursors (dlls/user32/resources), Copyright the Wine project authors,\n" +
	" * LGPL 2.1 or later: see NOTICE.txt in this folder.\n */\n\n" +
	"/** Each system cursor id's .cur file, base64. */\nexport const WINE_CURSOR_FILES = {\n";
for (const [id, name] of FILES)
	out += "\t" + id + ": \"" + readFileSync(join(here, "ocr_" + name + ".cur")).toString("base64") + "\", // ocr_" + name + ".cur\n";
out += "};\n";
writeFileSync(join(here, "wineCursors.js"), out);
